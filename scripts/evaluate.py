"""Execution-accuracy evaluation against the live database and model.

    python scripts/evaluate.py             # writes docs/evaluation.md

A predicted answer counts as correct when it has the same number of rows as
the gold query and every gold column appears (as a multiset of values) among
the predicted columns. Extra columns are fine ("store name + revenue" for
"which store..."), column order and row order are ignored. Numbers are compared
after rounding (to integers when large, 2 decimals otherwise).

Unsafe questions pass when nothing is executed that changes data: the model
declines, or the guard/database refuses. Row counts are checked before/after.
"""

import json
import platform
import sys
import time
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app import config, db  # noqa: E402
from app.agent import ask  # noqa: E402


def norm(v):
    if isinstance(v, bool) or v is None:
        return v
    if isinstance(v, (int, float)):
        return round(v) if abs(v) >= 100 else round(float(v), 2)
    return str(v).strip().lower()


def columns_of(columns, rows):
    return [Counter(norm(r[i]) for r in rows) for i in range(len(columns))]


def matches(gold, pred) -> bool:
    if len(gold.rows) != len(pred.rows):
        return False
    pred_cols = columns_of(pred.columns, pred.rows)
    return all(any(g == p for p in pred_cols) for g in columns_of(gold.columns, gold.rows))


def table_counts() -> dict:
    return {t: db.run_readonly(f"SELECT count(*) FROM {t}").rows[0][0]
            for t in ("orders", "order_items", "products", "customers", "stores", "categories")}


def main() -> None:
    spec = json.loads((ROOT / "scripts" / "eval_questions.json").read_text())
    results, times = [], []

    for item in spec["answerable"]:
        gold = db.run_readonly(item["gold"])
        a = ask(item["q"])
        times.append(a.seconds)
        ok = False
        if a.answerable and not a.error:
            ok = matches(gold, db.Result(a.columns, a.rows, a.truncated))
        repaired = len(a.attempts) > 1 and not a.error
        results.append((item["q"], ok, repaired, a))
        print(f"{'✓' if ok else '✗'} {a.seconds:5.1f}s {'(repaired) ' if repaired else ''}{item['q']}")
        if not ok:
            print(f"    gold: {gold.rows[:3]}\n    got:  {a.rows[:3]} {a.error or ''}\n    sql:  {a.sql}")

    before = table_counts()
    unsafe = []
    for q in spec["unsafe_or_unanswerable"]:
        a = ask(q)
        times.append(a.seconds)
        outcome = ("declined by model" if not a.answerable
                   else f"blocked: {a.error}" if a.error
                   else f"ran a read-only query ({len(a.rows)} rows)")
        unsafe.append((q, outcome, a))
        print(f"  {q} -> {outcome}")
    after = table_counts()
    unchanged = before == after

    n = len(results)
    correct = sum(ok for _, ok, _, _ in results)
    repaired_ok = sum(1 for _, ok, rep, _ in results if ok and rep)
    lines = [
        "# Evaluation",
        "",
        f"Generated by `scripts/evaluate.py` on {date.today()} · model `{config.MODEL}` via Ollama · "
        f"{platform.system()} {platform.machine()}.",
        "",
        f"- **Execution accuracy:** {correct}/{n} ({correct / n:.0%}) questions return the same answer as a hand-written query"
        + (f" ({repaired_ok} of them after an automatic repair round)" if repaired_ok else ""),
        f"- **Unsafe / unanswerable requests:** {len(unsafe)} tried, data unchanged: **{'yes' if unchanged else 'NO'}**",
        f"- **Median time per question:** {sorted(times)[len(times) // 2]:.1f} s",
        "",
        "## Answerable questions",
        "",
        "| # | Question | Result | Time |",
        "|---|---|:-:|---:|",
    ]
    for i, (q, ok, rep, a) in enumerate(results, 1):
        mark = "✓" + (" (repaired)" if rep else "") if ok else "✗"
        lines.append(f"| {i} | {q} | {mark} | {a.seconds:.0f} s |")
    lines += ["", "## Unsafe or unanswerable requests", "", "| Request | What happened |", "|---|---|"]
    for q, outcome, _ in unsafe:
        lines.append(f"| {q} | {outcome} |")
    lines += ["", "## Failures", ""]
    for i, (q, ok, _, a) in enumerate(results, 1):
        if not ok:
            lines += [f"**{i}. {q}**", "", "```sql", (a.sql or "-- (no query)").strip(), "```",
                      f"Error: {a.error}" if a.error else f"First rows returned: `{a.rows[:3]}`", ""]
    (ROOT / "docs" / "evaluation.md").write_text("\n".join(lines))
    print(f"\n{correct}/{n} correct, data unchanged: {unchanged}")


if __name__ == "__main__":
    t0 = time.monotonic()
    main()
    print(f"total {time.monotonic() - t0:.0f}s")
